/**
 * Veinticuatro personajes: dos por clase, ninguno parecido al otro.
 *
 * Sirven para tres cosas y por eso viven en el repositorio y no en un script
 * suelto:
 *
 * 1. **Mesa de prueba.** Doce clases, niveles de 2 a 17, lanzadores completos,
 *    a medias y ninguno; con subclase, con dote, con multiclase. Es el corpus
 *    que hace pasar al derivador por casi todo lo que sabe hacer.
 * 2. **Datos de demostración.** Códigos que se pueden pasar a alguien para que
 *    vea el Vault con personajes de verdad y no con un mago de ejemplo.
 * 3. **Detector de regresiones.** `veinticuatro.ts` los resuelve a todos e
 *    imprime cada referencia que no resolvió. Un id que se rompe al cambiar el
 *    índice aparece acá antes que en una mesa.
 *
 * Los ids no están escritos de memoria: salen de `probes/ids.ts` y
 * `probes/buscar-ids.ts`, que los leen del propio catálogo.
 *
 * Las puntuaciones son la matriz estándar (15, 14, 13, 12, 10, 8) repartida
 * según la clase, y `abilityBonuses` lleva el bono de linaje del PHB. Las dos
 * cosas son campos que el jugador edita, no números derivados: el constructor
 * los suma en `applyAbilityBonuses` junto con lo que den las mejoras y las
 * dotes.
 */

